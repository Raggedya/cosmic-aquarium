function normalizedIndex(value) {
  const length = MELBOURNE_CULTURE_SEGMENTS.length;
  const number = Number.isFinite(Number(value)) ? Math.trunc(Number(value)) : 0;
  return ((number % length) + length) % length;
}

export function getMelbourneCultureSegments(universe, startIndex = 0, count = 2) {
  if (String(universe || '').trim().toLowerCase() !== 'melbourne') return [];
  const safeCount = Math.max(0, Math.min(MELBOURNE_CULTURE_SEGMENTS.length, Math.trunc(Number(count) || 0)));
  const start = normalizedIndex(startIndex);
  return Array.from({length:safeCount},(_,offset)=>MELBOURNE_CULTURE_SEGMENTS[(start+offset)%MELBOURNE_CULTURE_SEGMENTS.length]);
}

export function advanceMelbourneCultureIndex(startIndex = 0, count = 2) {
  return normalizedIndex(normalizedIndex(startIndex) + Math.max(0,Math.trunc(Number(count) || 0)));
}
